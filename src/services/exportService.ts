import { jsPDF } from 'jspdf';
import type { ActionPlan, VerificationAudit, SkillFrequencyItem, ResumeEvidenceItem, UserProfile } from '../types/agent';

export interface ExportDataPayload {
  profile: UserProfile;
  plan: ActionPlan;
  audit: VerificationAudit | null;
  frequencies: SkillFrequencyItem[];
  benchmarkItems?: ResumeEvidenceItem[];
}

/**
 * Downloads a well-formatted Markdown document of the Career Transition Analysis
 */
export function exportAsMarkdown({ profile, plan, audit, frequencies, benchmarkItems }: ExportDataPayload): void {
  const dateStr = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
  const totalWeeks = plan.curriculumWeeks?.length || 6;
  const weeklyHours = plan.weeklyHours || profile.hoursPerWeek || 12;

  let md = `# RoleSync - Career Transition & Skill-Gap Analysis Report\n\n`;
  md += `**Date:** ${dateStr}\n`;
  md += `**Candidate:** ${profile.name || 'Anonymous Candidate'}\n`;
  md += `**Current Role:** ${profile.currentRole || 'Not specified'}\n`;
  md += `**Target Role:** ${profile.targetRole || 'Not specified'}\n`;
  md += `**Target Location:** ${profile.targetCity || 'Remote / Global'}\n`;
  md += `**Weekly Study Commitment:** ${weeklyHours} hours/week\n`;
  md += `**Total Roadmap Duration:** ${totalWeeks} weeks (~${totalWeeks * weeklyHours} total hours)\n\n`;

  md += `---\n\n`;
  md += `## 1. Market Demand & Skill Frequency Analysis\n\n`;
  md += `| Skill | Category | Employer Demand | Evidence in Resume |\n`;
  md += `|---|---|---|---|\n`;
  frequencies.forEach(item => {
    const bench = benchmarkItems?.find(b => b.skill === item.skill);
    const statusText = bench?.status === 'verified_evidence' 
      ? 'Verified in Resume' 
      : bench?.status === 'critical_gap'
      ? 'Critical Gap'
      : 'Secondary Gap';
    md += `| **${item.skill}** | ${item.category} | ${item.percentage}% (${item.count} postings) | ${statusText} |\n`;
  });

  md += `\n---\n\n`;
  md += `## 2. Top Identified Priority Skill Gaps\n\n`;
  plan.topThreeGaps.forEach((gap, idx) => {
    md += `### Priority ${idx + 1}: ${gap.skill} (${gap.marketPercentage}% Market Demand)\n`;
    md += `${gap.reasoning}\n\n`;
  });

  md += `---\n\n`;
  md += `## 3. Personalized ${totalWeeks}-Week Learning Curriculum\n\n`;
  plan.curriculumWeeks.forEach(cw => {
    md += `### Week ${cw.week}: ${cw.skill} (${cw.allocatedHours} hrs)\n`;
    md += `**Weekly Goal:** ${cw.weeklyGoal}\n\n`;
    md += `**Recommended Milestone:** ${cw.recommendedMilestone}\n\n`;
  });

  if (plan.curatedResources && plan.curatedResources.length > 0) {
    md += `---\n\n`;
    md += `## 4. Curated 100% Free Learning Resources\n\n`;
    plan.curatedResources.forEach(res => {
      md += `- **[${res.title}](${res.url})**\n`;
      md += `  - *Skill:* ${res.skill} | *Provider:* ${res.provider} | *Type:* ${res.type}\n`;
      md += `  - *Estimated Time:* ~${res.estimatedHours} hours | *Difficulty:* ${res.difficulty}\n\n`;
    });
  }

  if (audit) {
    md += `---\n\n`;
    md += `## 5. Verification & Grounding Audit\n\n`;
    md += `- **All Verification Checks Passed:** ${audit.allPassed ? 'YES' : 'NO'}\n`;
    md += `- **Live Citing Jobs Verified:** ${audit.jobCitationsChecked.length} URLs (HTTP 200)\n`;
    md += `- **Curated Learning Resources Verified:** ${audit.resourceLinksChecked.length} links verified live\n\n`;
  }

  md += `---\n*Generated by RoleSync - Agentic AI Career Transition Engine.*\n`;

  const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  const safeName = (profile.name || 'Candidate').replace(/[^a-zA-Z0-9_-]/g, '_');
  a.download = `RoleSync_${safeName}_Career_Roadmap.md`;
  a.click();
  URL.revokeObjectURL(url);
}

/**
 * Downloads raw JSON data for reporting or integration
 */
export function exportAsJSON({ profile, plan, audit, frequencies, benchmarkItems }: ExportDataPayload): void {
  const data = {
    system: 'RoleSync Career Transition Engine',
    generatedAt: new Date().toISOString(),
    candidateProfile: profile,
    marketSkillFrequencies: frequencies,
    resumeEvidenceAudit: benchmarkItems || [],
    actionPlan: plan,
    verificationAudit: audit
  };

  const jsonStr = JSON.stringify(data, null, 2);
  const blob = new Blob([jsonStr], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  const safeName = (profile.name || 'Candidate').replace(/[^a-zA-Z0-9_-]/g, '_');
  a.download = `RoleSync_${safeName}_Data.json`;
  a.click();
  URL.revokeObjectURL(url);
}

/**
 * Generates an executive PDF document using jsPDF
 */
export function exportAsPDF({ profile, plan, audit, frequencies, benchmarkItems }: ExportDataPayload): void {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  let y = 18;

  // Header Bar
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, pageWidth, 28, 'F');

  // Title
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.setTextColor(255, 255, 255);
  doc.text('RoleSync', 14, 13);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(251, 146, 60); // orange-400
  doc.text('Career Transition & Skill-Gap Executive Report', 14, 20);

  doc.setTextColor(148, 163, 184); // slate-400
  doc.setFontSize(8);
  const dateStr = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' });
  doc.text(`Generated: ${dateStr}`, pageWidth - 14, 20, { align: 'right' });

  y = 36;

  // Candidate Profile Box
  doc.setFillColor(248, 250, 252); // slate-50
  doc.setDrawColor(226, 232, 240); // slate-200
  doc.roundedRect(14, y, pageWidth - 28, 25, 2, 2, 'FD');

  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text(`Candidate: ${profile.name || 'Anonymous Candidate'}`, 18, y + 7);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  doc.text(`Current Background: ${profile.currentRole || 'N/A'}`, 18, y + 14);
  doc.text(`Target Role: ${profile.targetRole || 'N/A'} (${profile.targetCity || 'Remote'})`, 18, y + 20);

  doc.text(`Commitment: ${profile.hoursPerWeek} hrs/week`, pageWidth - 20, y + 14, { align: 'right' });
  doc.text(`Roadmap: ${plan.curriculumWeeks?.length || 6} Weeks`, pageWidth - 20, y + 20, { align: 'right' });

  y += 32;

  // Section 1: Market Demand & Gap Analysis
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text('1. Market Skill Demand vs. Candidate Evidence', 14, y);
  y += 6;

  // Table header
  doc.setFillColor(241, 245, 249);
  doc.rect(14, y, pageWidth - 28, 7, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(71, 85, 105);
  doc.text('SKILL', 18, y + 5);
  doc.text('CATEGORY', 65, y + 5);
  doc.text('EMPLOYER DEMAND', 115, y + 5);
  doc.text('STATUS', pageWidth - 20, y + 5, { align: 'right' });
  y += 8;

  // Render top skills
  const topSkills = frequencies.slice(0, 7);
  topSkills.forEach((item) => {
    const bench = benchmarkItems?.find(b => b.skill === item.skill);
    const isVerified = bench?.status === 'verified_evidence';

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(15, 23, 42);
    doc.text(item.skill, 18, y + 4);

    doc.setTextColor(100, 116, 139);
    doc.text(item.category, 65, y + 4);

    doc.text(`${item.percentage}% (${item.count} jobs)`, 115, y + 4);

    if (isVerified) {
      doc.setTextColor(22, 101, 52); // green-800
      doc.setFont('helvetica', 'bold');
      doc.text('In Resume', pageWidth - 20, y + 4, { align: 'right' });
    } else {
      doc.setTextColor(194, 65, 12); // orange-700
      doc.setFont('helvetica', 'bold');
      doc.text('Identified Gap', pageWidth - 20, y + 4, { align: 'right' });
    }

    doc.setDrawColor(241, 245, 249);
    doc.line(14, y + 6, pageWidth - 14, y + 6);
    y += 7;
  });

  y += 5;

  // Section 2: Recommended Curriculum Weeks
  if (y > 210) {
    doc.addPage();
    y = 20;
  }

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text(`2. Personalized Curriculum (${plan.curriculumWeeks?.length || 6} Weeks)`, 14, y);
  y += 7;

  plan.curriculumWeeks.slice(0, 4).forEach((cw) => {
    if (y > 250) {
      doc.addPage();
      y = 20;
    }

    doc.setFillColor(248, 250, 252);
    doc.setDrawColor(226, 232, 240);
    doc.roundedRect(14, y, pageWidth - 28, 17, 1.5, 1.5, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(15, 23, 42);
    doc.text(`Week 0${cw.week}: ${cw.skill}`, 18, y + 5.5);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(234, 88, 12); // orange-600
    doc.text(`${cw.allocatedHours} hrs/week`, pageWidth - 20, y + 5.5, { align: 'right' });

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(71, 85, 105);
    const goalText = doc.splitTextToSize(`Goal: ${cw.weeklyGoal}`, pageWidth - 40);
    doc.text(goalText[0] || '', 18, y + 11);

    y += 20;
  });

  // Section 3: Verification & Quality Audit
  if (audit) {
    if (y > 235) {
      doc.addPage();
      y = 20;
    }

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(15, 23, 42);
    doc.text('3. Plan Feasibility & Traceability Audit', 14, y);
    y += 7;

    doc.setFillColor(240, 253, 244); // green-50
    doc.setDrawColor(187, 247, 208); // green-200
    doc.roundedRect(14, y, pageWidth - 28, 15, 1.5, 1.5, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(21, 128, 61); // green-700
    doc.text('Verification Status: PASSED (All Citations & Resources Tested HTTP 200)', 18, y + 5.5);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(55, 65, 81);
    doc.text(`${audit.jobCitationsChecked.length} citing job URLs verified live | ${audit.resourceLinksChecked.length} free learning resources tested`, 18, y + 10.5);

    y += 19;
  }

  // Footer
  doc.setFontSize(7.5);
  doc.setTextColor(148, 163, 184);
  doc.text('RoleSync Skill-Gap & Career Transition Engine - Confidential Report', 14, doc.internal.pageSize.getHeight() - 8);

  const safeName = (profile.name || 'Candidate').replace(/[^a-zA-Z0-9_-]/g, '_');
  doc.save(`RoleSync_${safeName}_Executive_Report.pdf`);
}
